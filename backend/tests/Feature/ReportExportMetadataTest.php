<?php

namespace Tests\Feature;

use App\Models\Brand;
use App\Models\Category;
use App\Models\Order;
use App\Models\Product;
use App\Models\SalesTransaction;
use App\Models\User;
use App\Services\ReportService;
use Carbon\Carbon;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Laravel\Sanctum\Sanctum;
use Tests\TestCase;

class ReportExportMetadataTest extends TestCase
{
    use RefreshDatabase;

    protected User $admin;
    protected ReportService $reportService;

    protected function setUp(): void
    {
        parent::setUp();

        $this->reportService = app(ReportService::class);

        $this->admin = User::factory()->create([
            'name' => 'Maria Clara',
            'email' => 'admin.reports@jem.com',
            'role' => 'admin',
            'status' => 'active',
        ]);
    }

    public function test_resolve_generated_by_retrieves_admin_full_name_and_role(): void
    {
        $generatedBy = $this->reportService->resolveGeneratedBy($this->admin);
        $this->assertEquals('Maria Clara (Admin)', $generatedBy);
    }

    public function test_resolve_generated_by_falls_back_when_no_user(): void
    {
        $generatedBy = $this->reportService->resolveGeneratedBy(null);
        $this->assertEquals('System Automated / Scheduler', $generatedBy);
    }

    public function test_csv_sanitizer_prevents_formula_injection(): void
    {
        // Formulas starting with =, +, -, @
        $this->assertEquals("'=SUM(A1:A10)", $this->reportService->sanitizeCsvField('=SUM(A1:A10)'));
        $this->assertEquals("'+123456", $this->reportService->sanitizeCsvField('+123456'));
        $this->assertEquals("'-100", $this->reportService->sanitizeCsvField('-100'));
        $this->assertEquals("'@cmd", $this->reportService->sanitizeCsvField('@cmd'));

        // Normal strings and quotes
        $this->assertEquals('Normal Text', $this->reportService->sanitizeCsvField('Normal Text'));
        $this->assertEquals('He said ""Hello""', $this->reportService->sanitizeCsvField('He said "Hello"'));
    }

    public function test_monthly_sales_csv_export_includes_metadata_header_and_daily_breakdown(): void
    {
        $monthlyReport = $this->reportService->monthlySalesReport(2026, 10);
        $csv = $this->reportService->exportToCSV($monthlyReport, 'monthly', $this->admin, [
            'period' => '10/2026'
        ]);

        $this->assertStringContainsString('Report Title,Monthly Sales Report (10/2026)', $csv);
        $this->assertStringContainsString('Generated Date,', $csv);
        $this->assertStringContainsString('Generated By,"Maria Clara (Admin)"', $csv);
        $this->assertStringContainsString("Status,Official Report\n---", $csv);
        $this->assertStringContainsString('DAY / DATE,SALES AMOUNT,ORDERS COUNT', $csv);
    }

    public function test_csv_export_handles_malicious_admin_name_safely(): void
    {
        $maliciousAdmin = User::factory()->make([
            'name' => '=HYPERLINK("http://evil.com")',
            'role' => 'admin',
        ]);

        $monthlyReport = $this->reportService->monthlySalesReport(2026, 10);
        $csv = $this->reportService->exportToCSV($monthlyReport, 'monthly', $maliciousAdmin);

        // Should be prefixed with a single quote to prevent spreadsheet execution
        $this->assertStringContainsString('Generated By,"\'=HYPERLINK(""http://evil.com"") (Admin)"', $csv);
    }

    public function test_api_admin_monthly_csv_endpoint_streams_csv_with_admin_metadata(): void
    {
        Sanctum::actingAs($this->admin);

        $response = $this->get('/api/admin/reports/monthly/csv?year=2026&month=10');
        $response->assertStatus(200);
        $response->assertHeader('Content-Type', 'text/csv; charset=UTF-8');

        $content = $response->streamedContent();
        $this->assertStringContainsString('Report Title,Monthly Sales Report (10/2026)', $content);
        $this->assertStringContainsString('Generated By,"Maria Clara (Admin)"', $content);
        $this->assertStringContainsString('Status,Official Report', $content);
        $this->assertStringContainsString('DAY / DATE,SALES AMOUNT,ORDERS COUNT', $content);
    }

    public function test_api_admin_reports_json_includes_generated_by_in_meta(): void
    {
        Sanctum::actingAs($this->admin);

        $response = $this->getJson('/api/admin/reports/monthly?year=2026&month=10');
        $response->assertStatus(200)
            ->assertJson([
                'success' => true,
                'meta' => [
                    'generated_by' => 'Maria Clara (Admin)',
                ],
            ]);
    }
}
